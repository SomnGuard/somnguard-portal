export type I18nKey = keyof (typeof dict)['es'];

function initialLang(): AppLanguage {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'es') return saved;
  } catch { /* noop */ }
  const nav = (navigator.language || 'es').toLowerCase();
  return nav.startsWith('en') ? 'en' : 'es';
}

interface LangState {
  lang: AppLanguage;
  setLang: (l: AppLanguage) => void;
  t: (key: I18nKey) => string;
}

const LangContext = createContext<LangState | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<AppLanguage>(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch { /* noop */ }
  }, [lang]);

  const setLang = useCallback((l: AppLanguage) => setLangState(l), []);
  const t = useCallback((key: I18nKey) => dict[lang][key] ?? dict.es[key] ?? key, [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang(): LangState {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error('useLang must be used within LanguageProvider');
  return ctx;
}
